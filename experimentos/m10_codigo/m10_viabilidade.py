#!/usr/bin/env python3
"""Viability criteria 2 and 3 of the M10 amendment (docs/decisao_tokenizador_codigo.md).

Criterion 2: the trained model's validation bits per byte against two no-context references on the
same validation partition, the unigram entropy of the symbols the model predicts and, for the code
arms, the unigram entropy of the code units (resultados/m10/medidas_morfema.json and medidas_codigo.json).
Criterion 3: samples generated by the code-arm models decoded back to text, counting invalid
codewords and an incomplete codeword at the end.

    python experimentos/m10_codigo/m10_viabilidade.py --dispositivo cuda
"""
import argparse
import collections
import json
import math
import sys
from pathlib import Path

import numpy as np
import torch

AQUI = Path(__file__).resolve().parent
RAIZ = AQUI.parents[1]
SAIDA = RAIZ / "resultados" / "m10"
sys.path.insert(0, str(RAIZ))
from slm.corpus import ler_documentos  # noqa: E402
from slm.geracao import gerar_ar  # noqa: E402
from slm.tokenizador import ESPECIAIS, carregar_tokenizador  # noqa: E402

EOS = ESPECIAIS["[EOS]"]

sys.path.insert(0, str(RAIZ / "scripts"))
from m11 import carregar_corrida  # noqa: E402

PLANO = json.loads((SAIDA / "m10_plano.json").read_text(encoding="utf-8"))
UNIDADES = {"C1": ("medidas_morfema.json", "mista 4096 prefixo"), "C2": ("medidas_morfema.json", "mista 4096 prefixo"),
            "C3": ("medidas_codigo.json", "mista 4096")}


def bpb_corridas(braco, janela, ponto):
    vals = []
    for s in (0, 1, 2):
        p = RAIZ / "runs" / f"m10-{braco}-{janela}-e{ponto}-s{s}-aut" / "avaliacao.json"
        if p.exists():
            vals.append(json.loads(p.read_text())["bpb"])
    return vals


def unigrama_simbolos(tok, treino, valid):
    c = collections.Counter(i for t in treino for i in tok.encode(t))
    tot = sum(c.values()) + tok.vocab_size
    ids = [i for t in valid for i in tok.encode(t)]
    B = sum(len(t.encode("utf-8")) for t in valid)
    return -sum(math.log2((c[i] + 1) / tot) for i in ids) / B


def unigrama_unidades(braco):
    if braco not in UNIDADES:
        return None
    arq, rotulo = UNIDADES[braco]
    linhas = json.loads((SAIDA / arq).read_text(encoding="utf-8"))["linhas"]
    return next(r["xent_unidades_por_byte"] for r in linhas if r["unidade"] == rotulo)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dispositivo", default="cpu")
    ap.add_argument("--amostras", type=int, default=32)
    a = ap.parse_args()
    treino = [d["texto"] for d in ler_documentos("A", "treino")]
    valid = [d["texto"] for d in ler_documentos("A", "validacao")]
    res = {"criterio_2": {}, "criterio_3": {}}
    for braco, b in PLANO["bracos"].items():
        tok = carregar_tokenizador(RAIZ / b["pasta"])
        ref = {"unigrama_simbolos": unigrama_simbolos(tok, treino, valid), "unigrama_unidades": unigrama_unidades(braco)}
        for ponto in (16, 256):
            for janela in b["janelas"]:
                v = bpb_corridas(braco, janela, ponto)
                if v:
                    res["criterio_2"][f"{braco}-{janela}-e{ponto}"] = {"bpb_medio": float(np.mean(v)), "sementes": len(v), **ref}
        if braco.startswith("C"):
            for ponto in (16, 256):
                rid = f"m10-{braco}-simbolos-e{ponto}-s0-aut"
                if not (RAIZ / "runs" / rid / "pesos.pt").exists():
                    continue
                cfg, _, modelo, tokc = carregar_corrida(rid, a.dispositivo)
                w = gerar_ar(modelo, cfg.L, n=a.amostras, semente=11, dispositivo=a.dispositivo)
                invalidas, incompletas, textos = 0, 0, []
                for r in w.tolist():
                    ids = r[: r.index(EOS)] if EOS in r else r
                    tokc.invalidos = 0
                    texto = tokc.decode(ids)
                    invalidas += tokc.invalidos > 0
                    textos.append(texto.decode("utf-8", "replace"))
                    buf = ()
                    for i in ids:
                        buf += (i - 4,)
                        if buf in tokc.trie:
                            buf = ()
                    incompletas += len(buf) > 0
                res["criterio_3"][rid] = {"amostras": a.amostras, "com_palavra_invalida": invalidas,
                                          "com_palavra_incompleta_no_fim": incompletas, "exemplos": textos[:3]}
    (SAIDA / "m10_viabilidade.json").write_text(json.dumps(res, indent=1, ensure_ascii=False), encoding="utf-8")
    for k, v in res["criterio_2"].items():
        print(f"{k:24s} bpb {v['bpb_medio']:.3f} | unigrama simbolos {v['unigrama_simbolos']:.3f} | unigrama unidades {v['unigrama_unidades']}")
    for k, v in res["criterio_3"].items():
        print(k, {kk: vv for kk, vv in v.items() if kk != "exemplos"})
        print("   ", v["exemplos"][0][:300].replace("\n", " "))


if __name__ == "__main__":
    main()
